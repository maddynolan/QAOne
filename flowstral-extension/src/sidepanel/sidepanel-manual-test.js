/**
 * Sidepanel Manual Test Conversion helpers
 * Extracted from SidebarController — loaded via <script> before sidepanel.js
 * These are standalone functions invoked by one-liner delegates in the class.
 */

/**
 * Convert workflow to manual test case.
 * @param {object} ctx - SidebarController instance
 */
function spConvertToManualTest(ctx) {
  if (ctx.workflowSteps.length === 0) {
    ctx.addLog('error', 'No steps in workflow');
    return;
  }

  // Generate manual test case in ISTQB format
  const testCase = {
    id: `TC-${Date.now()}`,
    name: `Manual Test - ${new Date().toLocaleString()}`,
    description: 'Test case generated from recorded workflow',
    preconditions: `Navigate to: ${ctx.state.startUrl || ctx.state.pageAnalysis?.url || 'Application URL'}`,
    steps: ctx.workflowSteps.map((step, idx) => ({
      stepNumber: idx + 1,
      action: spGetManualTestAction(step),
      expectedResult: spGetExpectedResult(step)
    })),
    postconditions: 'Verify all steps completed successfully',
    priority: 'Medium',
    createdAt: new Date().toISOString()
  };

  // Format as readable text
  const manualTestText = spFormatManualTest(testCase);

  // Show in script preview
  if (ctx.elements.scriptPreview) {
    ctx.elements.scriptPreview.textContent = manualTestText;
  }

  // Switch to Script tab
  const scriptTab = document.querySelector('[data-tab="script"]');
  if (scriptTab) scriptTab.click();

  // Copy to clipboard
  navigator.clipboard?.writeText(manualTestText).then(() => {
    ctx.addLog('success', 'Manual test case copied to clipboard');
  }).catch(() => {
    ctx.addLog('info', 'Manual test case generated');
  });
}

/**
 * Get human-readable action for manual test.
 */
function spGetManualTestAction(step) {
  const actionVerbs = {
    'click': 'Click on',
    'fill': 'Enter value in',
    'select': 'Select from',
    'check': 'Check/Select',
    'assert': 'Verify'
  };

  const verb = actionVerbs[step.type] || 'Interact with';
  const element = step.element || 'element';
  const text = step.text || step.description;

  return `${verb} the "${text}" ${element}`;
}

/**
 * Get expected result for manual test step.
 */
function spGetExpectedResult(step) {
  const elementType = step.element || 'element';
  const text = step.text || '';

  switch (step.type) {
    case 'click':
      if (elementType === 'link') return 'Page navigates or action is triggered';
      if (elementType === 'button') return 'Action is performed successfully';
      if (elementType === 'radio' || elementType === 'checkbox') return 'Option is selected';
      return 'Element responds to click';
    case 'fill':
      return `Value "${step.value || 'entered text'}" is displayed in the field`;
    case 'select':
      return 'Selected option is displayed';
    case 'assert':
      return `"${text}" is visible on the page`;
    default:
      return 'Action completes successfully';
  }
}

