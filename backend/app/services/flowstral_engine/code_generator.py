    def _generate_test_function(self) -> List[str]:
        """Generate the test function."""
        lines = [
            '# ============================================================',
            '# TEST FUNCTION',
            '# ============================================================',
            '',
            '@pytest.fixture(scope="function")',
            'def browser_context():',
            '    """Create browser context for test."""',
            '    with sync_playwright() as p:',
            '        browser = p.chromium.launch(headless=False, slow_mo=100)',
            '        context = browser.new_context(viewport={"width": 1920, "height": 1080})',
            '        yield context',
            '        context.close()',
            '        browser.close()',
            '',
            '',
            f'def test_{self.test_name}(browser_context):',
            f'    """Auto-generated test: {self.test_name}"""',
            '    page = browser_context.new_page()',
            f'    engine = FlowstralEngine(page, app_type="{self.app_type}")',
            '    ',
            '    step_num = 0',
            '    step_error = None',
            '    ',
            '    try:',
        ]
        
        # Generate steps
        for i, step in enumerate(self.steps, 1):
            lines.append(f'        # Step {i}: {step.description}')
            lines.append(f'        step_num = {i}')
            lines.append(f'        print(f"[+] Step {i}: {step.description}")')
            lines.extend(self._generate_step_code(step))
            lines.append('')
        
        # Exception handling
        lines.extend([
            '        print("\\n" + "="*50)',
            '        print("[SUCCESS] All steps completed!")',
            '        print("="*50)',
            '        ',
            '    except Exception as e:',
            '        step_error = e',
            '        print(f"\\n[FAIL] Step {step_num} failed: {e}")',
            '        ',
            '        # Take screenshot',
            '        try:',
            f'            screenshot_path = f"failure_step_{{step_num}}_{self.test_name}.png"',
            '            page.screenshot(path=screenshot_path)',
            '            print(f"Screenshot saved: {screenshot_path}")',
            '        except:',
            '            pass',
            '        ',
            '        raise step_error',
            '    ',
            '    finally:',
            '        # Keep browser open briefly for debugging',
            '        time.sleep(3)',
            '',
        ])
        
        return lines
    
    def _generate_step_code(self, step: TestStep) -> List[str]:
        """Generate code for a single step."""
        lines = []
        indent = '        '
        
        action = step.action.lower()
        
        if action == 'navigate':
            url = (step.url or step.value or '').replace('"', '\\"').replace("'", "\\'")
            lines.append(f'{indent}engine.navigate("{url}")')
            
        elif action == 'click':
            args = self._build_element_args(step)
            lines.append(f'{indent}engine.click({args})')
            
        elif action in ['fill', 'input', 'type']:
            value = (step.value or '').replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'")
            args = self._build_element_args(step, include_value=False)
            lines.append(f'{indent}engine.fill("{value}", {args})')
            
        elif action == 'hover':
            args = self._build_element_args(step)
            lines.append(f'{indent}engine.hover({args})')
            
        elif action == 'sf_open_app':
            app_name = (step.value or step.target or '').replace('"', '\\"')
            lines.append(f'{indent}engine.sf_open_app("{app_name}")')
            
        elif action == 'sf_global_search':
            search_text = (step.value or '').replace('"', '\\"')
            lines.append(f'{indent}engine.sf_global_search("{search_text}")')
            
        elif action == 'sf_click_tab':
            tab_name = (step.target or step.value or '').replace('"', '\\"')
            lines.append(f'{indent}engine.sf_click_tab("{tab_name}")')
            
        elif action == 'sf_save':
            lines.append(f'{indent}engine.sf_save()')
            
        elif action == 'wait':
            ms = step.value or '1000'
            lines.append(f'{indent}engine.page.wait_for_timeout({ms})')
            
        elif action == 'press_key':
            key = (step.value or 'Enter').replace('"', '\\"')
            lines.append(f'{indent}engine.page.keyboard.press("{key}")')
            
        else:
            # Generic action - try to map to click/fill
            if step.value:
                args = self._build_element_args(step, include_value=False)
                value = step.value.replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'")
                lines.append(f'{indent}engine.fill("{value}", {args})')
            else:
                args = self._build_element_args(step)
                lines.append(f'{indent}engine.click({args})')
        
        return lines
    
    def _build_element_args(self, step: TestStep, include_value: bool = True) -> str:
        """Build argument string for element finding."""
        args = []
        
        # Extract text from description
        desc = step.description or ''
        target = step.target or ''
        
        # Try to detect meaningful text
        text = None
        
        # Check for quoted text in description
        quotes_match = re.search(r'"([^"]+)"', desc)
        if quotes_match:
            text = quotes_match.group(1)
        elif target:
            text = target
        
        # Detect role from description
        role = None
        desc_lower = desc.lower()
        
        if 'button' in desc_lower or 'click' in desc_lower:
            role = 'button'
        elif 'input' in desc_lower or 'fill' in desc_lower:
            role = 'textbox'
        elif 'link' in desc_lower:
            role = 'link'
        elif 'tab' in desc_lower:
            role = 'tab'
        elif 'checkbox' in desc_lower:
            role = 'checkbox'
        
        # Build args
        if text:
            args.append(f'text="{text}"')
        
        if role:
            args.append(f'role="{role}"')
        
        # Add selector hint if available
        if step.selector:
            selector = step.selector.replace('"', '\\"')
            args.append(f'selector_hint="{selector}"')
        
        # Add description
        clean_desc = desc.replace('"', '\\"')[:50]
        args.append(f'description="{clean_desc}"')
        
        return ', '.join(args)
    
    def _generate_main_block(self) -> List[str]:
        """Generate if __name__ == '__main__' block."""
        return [
            '',
            '# ============================================================',
            '# MAIN EXECUTION',
            '# ============================================================',
            '',
            'if __name__ == "__main__":',
            '    # Run with pytest for better output',
            '    import subprocess',
            '    exit_code = subprocess.call(["python", "-m", "pytest", __file__, "-v", "-s", "--tb=short"])',
            '    sys.exit(exit_code)',
        ]


