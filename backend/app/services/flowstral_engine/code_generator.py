"""
FLOWSTRAL CODE GENERATOR
========================
Generates robust Playwright test code using the Flowstral Engine.

Instead of generating raw Playwright selectors:
    page.locator('[data-aura-rendered-by="123:0"]').click()

We generate intent-based engine calls:
    engine.click(text="Save", role="button")
"""

import re
import json
from typing import List, Dict, Any, Optional
from dataclasses import dataclass


@dataclass
class TestStep:
    """Represents a single test step."""
    action: str  # click, fill, navigate, hover, etc.
    description: str  # Human-readable description
    target: Optional[str] = None  # Target element description
    value: Optional[str] = None  # Value for inputs
    selector: Optional[str] = None  # Original recorded selector (as hint)
    url: Optional[str] = None  # For navigate actions
    metadata: Dict = None  # Additional data


class FlowstralCodeGenerator:
    """
    Generates robust Python test code using the Flowstral Engine.
    
    The generated code uses semantic element finding instead of
    brittle CSS selectors, making tests more maintainable and
    self-healing.
    """
    
    def __init__(self, test_name: str, app_type: str = "auto"):
        self.test_name = self._sanitize_name(test_name)
        self.app_type = app_type
        self.steps: List[TestStep] = []
        self.imports = set()
        self.setup_code = []
    
    def _sanitize_name(self, name: str) -> str:
        """Sanitize test name for Python."""
        name = re.sub(r'[^a-zA-Z0-9_]', '_', name.lower())
        if name[0].isdigit():
            name = 'test_' + name
        return name
    
    def add_step(
        self,
        action: str,
        description: str,
        target: str = None,
        value: str = None,
        selector: str = None,
        url: str = None,
        **metadata
    ):
        """Add a test step."""
        self.steps.append(TestStep(
            action=action,
            description=description,
            target=target,
            value=value,
            selector=selector,
            url=url,
            metadata=metadata or {}
        ))
    
    def generate(self) -> str:
        """Generate the complete test file."""
        code_lines = []
        
        # === IMPORTS ===
        code_lines.extend(self._generate_imports())
        code_lines.append("")
        
        # === FLOWSTRAL ENGINE CLASS (embedded for portability) ===
        code_lines.extend(self._generate_embedded_engine())
        code_lines.append("")
        
        # === TEST FUNCTION ===
        code_lines.extend(self._generate_test_function())
        
        # === MAIN BLOCK ===
        code_lines.extend(self._generate_main_block())
        
        return "\n".join(code_lines)
    
    def _generate_imports(self) -> List[str]:
        """Generate import statements."""
        return [
            '"""',
            f'Test: {self.test_name}',
            f'Generated by Flowstral Engine',
            f'App Type: {self.app_type}',
            '"""',
            '',
            'import sys',
            'import time',
            'import re',
            'from typing import Optional, List, Dict, Any',
            'from playwright.sync_api import sync_playwright, Page, Locator',
            'import pytest',
            '',
        ]
    
