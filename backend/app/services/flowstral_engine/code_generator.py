def generate_test_from_steps(
    test_name: str,
    steps: List[Dict[str, Any]],
    app_type: str = "auto"
) -> str:
    """
    Generate a test file from a list of step dictionaries.
    
    Args:
        test_name: Name for the test
        steps: List of step dicts with keys: action, description, target, value, selector
        app_type: Application type (salesforce, servicenow, etc.)
        
    Returns:
        Complete Python test file content
    """
    generator = FlowstralCodeGenerator(test_name, app_type)
    
    for step in steps:
        generator.add_step(
            action=step.get('action', 'click'),
            description=step.get('description', step.get('name', '')),
            target=step.get('target'),
            value=step.get('value'),
            selector=step.get('selector'),
            url=step.get('url'),
        )
    
    return generator.generate()

